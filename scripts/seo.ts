// Runs before every build/serve. Validates the posts, then writes:
//   src/app/data/posts.gen.ts (post metadata, tags, week strip), calendar.gen.ts, loaders.gen.ts and
//   articles/<slug>.ts (post body + only its media records, one lazy chunk per article)
//   public/sitemap.xml, public/robots.txt, public/rss.xml, public/search.json
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { FEATURED, KINDS, MOST_READ, SECTIONS, SITE_NAME, SITE_TAGLINE, SITE_URL, AUTHORS } from '../src/app/data/site.ts';
import { plain, poster, record, slugify, titleOf, wide } from '../src/app/data/media.ts';
import type { Block, CalendarItem, Media, Post, PostMeta, Ref, WeekItem } from '../src/app/data/types.ts';

const root = new URL('../', import.meta.url);
const media = JSON.parse(await readFile(new URL('src/app/data/media.json', root), 'utf8')) as Media;
const dir = new URL('src/app/data/posts/', root);
const files = (await readdir(dir)).filter((f) => f.endsWith('.ts')).sort();
const posts: Post[] = [];
for (const f of files) posts.push(((await import(new URL(f, dir).href)) as { post: Post }).post);
posts.sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));

// ---------- validation: fail the build on broken content ----------
const errors: string[] = [];
const slugs = new Set(posts.map((p) => p.slug));
const blockText = (b: Block): string[] =>
  'p' in b ? [b.p] : 'h2' in b ? [b.h2] : 'quote' in b ? [b.quote] : 'img' in b ? [b.caption] : 'list' in b ? b.list
    : 'box' in b ? [b.box, b.title ?? ''] : 'entry' in b ? [b.title ?? '', ...b.text] : [];
const blockRefs = (b: Block): Ref[] => ('img' in b ? [b.img] : 'ficha' in b ? [b.ficha] : 'entry' in b ? [b.entry] : []);
const EM_DASH = String.fromCharCode(0x2014);
for (const p of posts) {
  if (!files.includes(`${p.slug}.ts`)) errors.push(`${p.slug}: file name must be the slug`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(p.date)) errors.push(`${p.slug}: bad date`);
  if (p.dek.length < 70 || p.dek.length > 170) errors.push(`${p.slug}: dek has ${p.dek.length} chars (70 to 170)`);
  if (p.kind === 'review' && (p.score == null || !p.verdict)) errors.push(`${p.slug}: review needs score + verdict`);
  const texts = [p.title, p.dek, p.hero.alt, ...p.tags, ...p.body.flatMap(blockText), ...(p.verdict ? [p.verdict.summary, ...p.verdict.good, ...p.verdict.bad] : [])];
  if (texts.some((t) => t.includes(EM_DASH))) errors.push(`${p.slug}: em dash in text`);
  for (const t of texts) for (const m of t.matchAll(/\]\(\/artigo\/([^)]+)\)/g)) if (!slugs.has(m[1])) errors.push(`${p.slug}: link to missing post ${m[1]}`);
  for (const r of [p.hero.ref, ...p.body.flatMap(blockRefs)]) if (!record(media, r)) errors.push(`${p.slug}: ref ${r} not in media.json (run npm run media)`);
  if (!wide(media, p.hero.ref, p.hero.pick)) errors.push(`${p.slug}: hero has no image`);
}
for (const s of [FEATURED, ...MOST_READ]) if (!slugs.has(s)) errors.push(`site.ts references missing post ${s}`);
if (errors.length) {
  console.error(`seo: ${errors.length} problem(s)\n- ${errors.join('\n- ')}`);
  process.exit(1);
}

// ---------- metadata ----------
const words = (p: Post) => [p.dek, ...p.body.flatMap(blockText)].map(plain).join(' ').split(/\s+/).filter(Boolean).length;
const metas: PostMeta[] = posts.map((p) => {
  const { body, verdict, ...rest } = p;
  const n = words(p);
  return { ...rest, image: wide(media, p.hero.ref, p.hero.pick)!, thumb: wide(media, p.hero.ref, p.hero.pick, true)!, words: n, minutes: Math.max(1, Math.round(n / 200)), refs: [...new Set([p.hero.ref, ...body.flatMap(blockRefs)])] };
});

const tagMap = new Map<string, { slug: string; name: string; count: number }>();
for (const p of posts) for (const t of p.tags) {
  const s = slugify(t);
  const e = tagMap.get(s) ?? { slug: s, name: t, count: 0 };
  e.count++;
  tagMap.set(s, e);
}
const tags = [...tagMap.values()].sort((a, b) => b.count - a.count || a.name.localeCompare(b.name, 'pt-BR'));

// Calendar, precomputed: the browser never downloads media.json.
const calendar: CalendarItem[] = media.calendar.map((c) => ({
  ...c, kind: c.ref.split(':')[0] as CalendarItem['kind'], title: titleOf(media, c.ref), poster: poster(media, c.ref),
}));
// "Lançamentos da semana": the 7 days starting at the data snapshot date (deterministic for prerender).
const start = media.updatedAt;
const end = new Date(Date.parse(`${start}T12:00:00Z`) + 6 * 864e5).toISOString().slice(0, 10);
const week: WeekItem[] = calendar.filter((c) => c.date >= start && c.date <= end).map(({ date, ref, title, note, poster }) => ({ date, ref, title, note, poster }));

const gen = `// Generated by scripts/seo.ts from src/app/data/posts/*.ts and media.json. Do not edit by hand.
import type { CalendarItem, PostMeta, WeekItem } from './types';

export const UPDATED = '${media.updatedAt}';

export const POSTS: PostMeta[] = ${JSON.stringify(metas, null, 1)};

export const TAGS: { slug: string; name: string; count: number }[] = ${JSON.stringify(tags)};

export const WEEK: WeekItem[] = ${JSON.stringify(week, null, 1)};
`;
await writeFile(new URL('src/app/data/posts.gen.ts', root), gen);
await writeFile(new URL('src/app/data/calendar.gen.ts', root), `// Generated by scripts/seo.ts from media.json. Do not edit by hand.
import type { CalendarItem } from './types';

export const CALENDAR: CalendarItem[] = ${JSON.stringify(calendar)};
`);

// One module per article: the post plus only the media records it cites (a few KB instead of all of media.json).
await mkdir(new URL('src/app/data/articles/', root), { recursive: true });
for (const m of metas) {
  const pick = (kind: 'game' | 'movie' | 'tv') => Object.fromEntries(m.refs.filter((r) => r.startsWith(`${kind}:`)).map((r) => [r.split(':')[1], record(media, r)!.r]));
  const slice: Media = { source: media.source, updatedAt: media.updatedAt, calendar: [], games: pick('game'), movies: pick('movie'), tv: pick('tv') };
  await writeFile(new URL(`src/app/data/articles/${m.slug}.ts`, root), `// Generated by scripts/seo.ts. Do not edit by hand.
import type { Media } from '../types';
export { post } from '../posts/${m.slug}';

export const media: Media = ${JSON.stringify(slice)};
`);
}
// Kept apart from POSTS so the route resolver does not pull the post index into the initial bundle.
await writeFile(new URL('src/app/data/loaders.gen.ts', root), `// Generated by scripts/seo.ts. Do not edit by hand.
import type { Media, Post } from './types';

export type Loaded = { post: Post; media: Media };

/** Each article loads as one lazy chunk (body + its media records), never on listing pages. */
export const LOAD: Record<string, () => Promise<Loaded>> = {
${posts.map((p) => `  '${p.slug}': () => import('./articles/${p.slug}'),`).join('\n')}
};
`);

// ---------- sitemap + robots ----------
const pages = [
  { path: '/', priority: '1.0', mod: posts[0].date },
  ...Object.values(SECTIONS).map((s) => ({ path: s.path, priority: '0.8', mod: posts[0].date })),
  { path: '/reviews/', priority: '0.8', mod: posts[0].date },
  { path: '/guias/', priority: '0.7', mod: posts[0].date },
  { path: '/lancamentos/', priority: '0.7', mod: media.updatedAt },
  ...AUTHORS.map((a) => ({ path: `/autor/${a.slug}/`, priority: '0.4', mod: posts[0].date })),
  ...tags.map((t) => ({ path: `/tag/${t.slug}/`, priority: '0.4', mod: posts.find((p) => p.tags.some((x) => slugify(x) === t.slug))!.date })),
  ...posts.map((p) => ({ path: `/artigo/${p.slug}/`, priority: '0.9', mod: p.date })),
];
const xml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
await writeFile(new URL('public/sitemap.xml', root), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${pages.map((p) => `  <url><loc>${SITE_URL}${p.path}</loc><lastmod>${p.mod}</lastmod><priority>${p.priority}</priority></url>`).join('\n')}
</urlset>
`);
// ponytail: a GitHub Pages project site cannot own the domain-root robots.txt; this copy documents intent.
await writeFile(new URL('public/robots.txt', root), `User-agent: *
Allow: /
Disallow: /G2HubBlog/busca/

Sitemap: ${SITE_URL}/sitemap.xml
`);

// ---------- RSS 2.0 ----------
const rfc822 = (d: string) => new Date(`${d}T12:00:00-03:00`).toUTCString();
const rss = `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:media="http://search.yahoo.com/mrss/">
<channel>
  <title>${xml(SITE_NAME)}: ${xml(SITE_TAGLINE)}</title>
  <link>${SITE_URL}/</link>
  <atom:link href="${SITE_URL}/rss.xml" rel="self" type="application/rss+xml"/>
  <description>Notícias, reviews e guias de games, filmes e séries. Projeto de portfólio com textos de demonstração.</description>
  <language>pt-BR</language>
  <lastBuildDate>${rfc822(posts[0].date)}</lastBuildDate>
${metas.map((p) => `  <item>
    <title>${xml(p.title)}</title>
    <link>${SITE_URL}/artigo/${p.slug}/</link>
    <guid isPermaLink="true">${SITE_URL}/artigo/${p.slug}/</guid>
    <pubDate>${rfc822(p.date)}</pubDate>
    <category>${xml(SECTIONS[p.section].label)}</category>
    <category>${xml(KINDS[p.kind])}</category>
    <description>${xml(p.dek)}</description>
    <media:content url="${xml(p.image.src)}" medium="image"/>
  </item>`).join('\n')}
</channel>
</rss>
`;
await writeFile(new URL('public/rss.xml', root), rss);

// ---------- search index (fetched only by /busca) ----------
const norm = (s: string) => s.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
const index = posts.map((p) => ({
  s: p.slug,
  t: norm(`${p.title} ${p.tags.join(' ')}`),
  x: norm([p.dek, ...p.body.flatMap(blockText), ...p.body.flatMap(blockRefs).map((r) => titleOf(media, r))].map(plain).join(' ')),
}));
await writeFile(new URL('public/search.json', root), JSON.stringify(index));

console.log(`seo: ${posts.length} posts, ${tags.length} tags, ${week.length} lançamentos na semana, sitemap ${pages.length} urls, rss, search.json`);
